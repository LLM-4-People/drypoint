/**
 * The complete card artwork.
 *
 * @param {{name:string, description:string, homepage:string}} brand
 * @returns {string} a complete SVG document with its generated-by header
 */
export function renderSocialSvg(brand) {
  const { width, height } = SOCIAL_CARD;
  const host = new URL(brand.homepage).hostname;
  const lines = taglineLines(brand.description);
  const size = taglineSize(lines);
  const pillWidth = Math.round(host.length * 15.1) + 52;
  const gridX = Array.from({ length: 9 }, (_, index) => `<line x1="${128 * (index + 1)}" y1="0" x2="${128 * (index + 1)}" y2="${height}"/>`);
  const gridY = Array.from({ length: 4 }, (_, index) => `<line x1="0" y1="${128 * (index + 1)}" x2="${width}" y2="${128 * (index + 1)}"/>`);
  const tagline = lines
    .map((line, index) => `<tspan x="72" dy="${index === 0 ? 0 : size + 8}">${text(line)}</tspan>`)
    .join('');

  return `<!-- ${HEADER} -->
<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img" aria-label="${attr(SOCIAL_CARD.alt)}">
  <defs>
    <radialGradient id="glow" cx="78%" cy="0%" r="72%">
      <stop offset="0" stop-color="${PALETTE.accent}" stop-opacity="0.20"/>
      <stop offset="0.45" stop-color="${PALETTE.accent}" stop-opacity="0.06"/>
      <stop offset="1" stop-color="${PALETTE.accent}" stop-opacity="0"/>
    </radialGradient>
    <filter id="label-shadow" x="-20%" y="-40%" width="140%" height="190%">
      <feDropShadow dx="0" dy="14" stdDeviation="14" flood-color="#000000" flood-opacity="0.55"/>
    </filter>
  </defs>
  <rect width="${width}" height="${height}" fill="${PALETTE.background}"/>
  <g stroke="${PALETTE.line}" stroke-width="1" opacity="0.55">
    ${gridX.join('\n    ')}
    ${gridY.join('\n    ')}
  </g>
  <rect width="${width}" height="${height}" fill="url(#glow)"/>
  <rect x="28.5" y="28.5" width="1223" height="583" rx="20" fill="none" stroke="${PALETTE.line2}"/>
  <g transform="translate(72 64) scale(${116 / 512})">
    ${labelMark(brand)}
  </g>
  <text x="72" y="292" font-family="${attr(FONT)}" font-size="104" font-weight="700" letter-spacing="-3" fill="${PALETTE.text}">${text(brand.name)}</text>
  <text x="72" y="344" font-family="${attr(FONT)}" font-size="${size}" fill="${PALETTE.muted}">${tagline}</text>
  <rect x="72" y="416" width="${pillWidth}" height="54" rx="27" fill="none" stroke="${PALETTE.accent}" stroke-width="2"/>
  <text x="98" y="451" font-family="${attr(MONO)}" font-size="25" fill="${PALETTE.accent}">${text(host)}</text>
  <text x="72" y="574" font-family="${attr(MONO)}" font-size="16" letter-spacing="2.4" fill="${PALETTE.muted}">OFFLINE LABEL STUDIO</text>
  <text x="348" y="574" font-family="${attr(MONO)}" font-size="16" letter-spacing="2.4" fill="${PALETTE.muted2}">NIIMBOT D110</text>
  ${backLabel()}
  ${frontLabel()}
</svg>
`;
}

/** Read the authored identity through the brand owner's validator. */
async function readBrand(root) {
  return parseBrand(await readFile(join(root, BRAND_FILE), 'utf8'));
}

/** Hex channel triplet, or null for a value that is not plain hex. */
function channels(value) {
  const match = /^#([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i.exec(value);
  return match ? { r: Number.parseInt(match[1], 16), g: Number.parseInt(match[2], 16), b: Number.parseInt(match[3], 16) } : null;
}

/** Whether a pixel is within one tolerance of a colour on every channel. */
function near(pixel, color, tolerance) {
  return (
    Math.abs(pixel.r - color.r) <= tolerance &&
    Math.abs(pixel.g - color.g) <= tolerance &&
    Math.abs(pixel.b - color.b) <= tolerance
  );
}

/** A pixel as `#rrggbb`, for a finding a person can compare with the design. */
function hex(pixel) {
  return `#${[pixel.r, pixel.g, pixel.b].map((value) => value.toString(16).padStart(2, '0')).join('')}`;
}

/**
 * Pure-Node findings for the committed card. The PNG is judged by its pixels,
 * never its bytes: Chromium antialiasing is not byte-stable across machines.
 *
 * @param {{root?: string, brand?: object}} [options]
 * @returns {Promise<{findings: string[], checked: number}>}
 */
export async function checkSocial({ root = ROOT, brand = null } = {}) {
  const findings = [];
  const identity = brand ?? (await readBrand(root));
  let svg = null;
  try {
    svg = await readFile(join(root, SOCIAL_CARD.svg), 'utf8');
  } catch (error) {
    findings.push(`${SOCIAL_CARD.svg}: ${error.message}`);
  }
  if (svg !== null) {
    if (!svg.startsWith(`<!-- ${HEADER} -->`)) {
      findings.push(`${SOCIAL_CARD.svg}: does not start with the generated-by header`);
    }
    if (svg !== renderSocialSvg(identity)) {
      findings.push(`${SOCIAL_CARD.svg}: is not renderSocialSvg(brand); run: npm run build:social -- --write`);
    }
  }

  let image;
  try {
    image = decodePng(await readFile(join(root, SOCIAL_CARD.png)));
  } catch (error) {
    findings.push(`${SOCIAL_CARD.png}: ${error.message}`);
    return { findings, checked: 1 };
  }
  if (image.width !== SOCIAL_CARD.width || image.height !== SOCIAL_CARD.height) {
    findings.push(`${SOCIAL_CARD.png}: ${image.width}x${image.height}, expected ${SOCIAL_CARD.width}x${SOCIAL_CARD.height}`);
  }

  const background = channels(PALETTE.background);
  const accent = channels(PALETTE.accent);
  const ink = channels(PALETTE.text);

  let transparentEdges = 0;
  for (let x = 0; x < image.width; x++) {
    if (pixelAt(image, x, 0).a !== 255) transparentEdges++;
    if (pixelAt(image, x, image.height - 1).a !== 255) transparentEdges++;
  }
  for (let y = 1; y < image.height - 1; y++) {
    if (pixelAt(image, 0, y).a !== 255) transparentEdges++;
    if (pixelAt(image, image.width - 1, y).a !== 255) transparentEdges++;
  }
  if (transparentEdges) findings.push(`${SOCIAL_CARD.png}: ${transparentEdges} edge pixels are not opaque`);

  // The bottom-left corner is the one quiet corner: the lime glow sits at the
  // top right, so this proves the base background rather than the gradient.
  const corner = pixelAt(image, 0, image.height - 1);
  if (!near(corner, background, 6)) {
    findings.push(`${SOCIAL_CARD.png}: the background corner is ${hex(corner)}, expected near ${PALETTE.background}`);
  }

  let accentPixels = 0;
  let textPixels = 0;
  let inkedPixels = 0;
  for (let y = 0; y < image.height; y++) {
    for (let x = 0; x < image.width; x++) {
      const pixel = pixelAt(image, x, y);
      if (near(pixel, accent, 12)) accentPixels++;
      if (x < image.width / 2 && near(pixel, ink, 10)) textPixels++;
      if (!near(pixel, corner, 8)) inkedPixels++;
    }
  }
  const total = image.width * image.height;
  const leftHalf = Math.floor(image.width / 2) * image.height;
  const accentShare = accentPixels / total;
  const textShare = textPixels / leftHalf;
  if (accentShare < 0.001) {
    findings.push(`${SOCIAL_CARD.png}: ${(accentShare * 100).toFixed(3)}% of pixels are near the accent, expected at least 0.1%`);
  }
  if (textShare < 0.003) {
    findings.push(`${SOCIAL_CARD.png}: ${(textShare * 100).toFixed(3)}% of the left half is near the text colour, expected at least 0.3%`);
  }
  if (inkedPixels / total < 0.005) findings.push(`${SOCIAL_CARD.png}: is blank`);

  return { findings, checked: 1 };
}

/** Write both card files atomically after one successful Chromium render. */
async function writeCard({ root = ROOT } = {}) {
  if (!CHROME) throw new Error('Chromium is required to regenerate the social card: set D110_CHROME or CHROME_PATH');
  const brand = await readBrand(root);
  const svg = renderSocialSvg(brand);
  const directory = await mkdtemp(join(tmpdir(), 'drypoint-social-'));
  try {
    const artwork = join(directory, 'social-card.svg');
    await writeFile(artwork, svg);
    const html = `<!doctype html><meta charset="utf-8"><style>
html,body{margin:0;width:${SOCIAL_CARD.width}px;height:${SOCIAL_CARD.height}px;overflow:hidden;background:${PALETTE.background}}
img{display:block;width:${SOCIAL_CARD.width}px;height:${SOCIAL_CARD.height}px}
</style><img src="${pathToFileURL(artwork).href}">`;
    const { image, png } = await screenshotHtml({
      html,
      width: SOCIAL_CARD.width,
      height: SOCIAL_CARD.height,
      directory,
      name: 'social-card',
      backgroundColor: '00000000',
    });
    if (image.width !== SOCIAL_CARD.width || image.height !== SOCIAL_CARD.height) {
      throw new Error(`Chromium rendered ${image.width}x${image.height}, expected ${SOCIAL_CARD.width}x${SOCIAL_CARD.height}`);
    }
    for (const [file, bytes] of [
      [SOCIAL_CARD.svg, svg],
      [SOCIAL_CARD.png, png],
    ]) {
      const target = join(root, file);
      const temporary = `${target}.${process.pid}.tmp`;
      await writeFile(temporary, bytes);
      await rename(temporary, target);
    }
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
  return { files: [SOCIAL_CARD.svg, SOCIAL_CARD.png] };
}

async function main(argv) {
  const flags = argv.filter((argument) => argument.startsWith('--'));
  const unknown = flags.filter((flag) => flag !== '--write' && flag !== '--check');
  if (unknown.length) {
    console.error(`social: unknown option ${unknown.join(', ')}`);
    console.error('usage: node scripts/build-social.mjs [--write|--check]');
    return 2;
  }
  try {
    if (flags.includes('--write')) {
      const { files } = await writeCard();
      const result = await checkSocial();
      if (result.findings.length) {
        for (const finding of result.findings) console.error(`social: ${finding}`);
        return 1;
      }
      console.log(`social: wrote ${files.join(', ')} (${SOCIAL_CARD.width}x${SOCIAL_CARD.height})`);
      return 0;
    }
    const result = await checkSocial();
    if (!result.findings.length) {
      console.log(`social: up to date (${result.checked} card, ${SOCIAL_CARD.width}x${SOCIAL_CARD.height})`);
      return 0;
    }
    for (const finding of result.findings) console.error(`social: ${finding}`);
    console.error('social: the generated card is stale; run: npm run build:social -- --write');
    return 1;
  } catch (error) {
    console.error(`social: ${error.message}`);
    return 1;
  }
}

const invokedDirectly = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) process.exitCode = await main(process.argv.slice(2));
