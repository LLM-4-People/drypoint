#!/usr/bin/env node
/**
 * Generates assets/precache.js from the real dependency graph and stamps the
 * matching content hash into sw.js as its BUILD constant:
 *
 *   index.html references (stylesheet, manifest, icons, classic scripts)
 *   → the ES module import graph rooted at src/main.js
 *   → every icon declared by manifest.webmanifest
 *   → every local CSS url() asset
 *
 * The output is deterministic: same inputs, same bytes. The service worker
 * imports the manifest and refuses to install when its BUILD stamp disagrees.
 *
 * Usage:
 *   node scripts/precache.mjs --write   # regenerate the manifest and stamp
 *   node scripts/precache.mjs --check   # exit 1 when either file differs
 */

import { createHash } from 'node:crypto';
import { readFile, realpath, rename, rm, stat, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

import { lexJavaScript } from './lib/js-scan.mjs';
import { BRAND } from '../src/core/brand.js';
import { injectBase } from './lib/base-href.mjs';
import { workerContentTypesSource } from './lib/content-types.mjs';
import { CONFIG } from '../src/core/config.js';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const OUTPUT = 'assets/precache.js';
export const SW_FILE = 'sw.js';
// Anchored: a comment that happens to contain a plausible stamp must never be
// rewritten in place of the real declaration.
const BUILD_PATTERN = /^const BUILD = '[0-9a-f]{16}';$/m;
// One generated block: the worker's `<base>` helper, authored and tested in
// scripts/lib/base-href.mjs. The markers make the block exactly-one, so a
// second copy or a missing block fails the build instead of shipping a stale
// rule.
const BASE_HELPER_BLOCK = /\/\/ BEGIN generated base helper\n[\s\S]*?\/\/ END generated base helper/;
// The worker's content-type map and its decision function are one generated
// block too: the module in scripts/lib is the only copy a person edits.
const CONTENT_TYPES_BLOCK = /\/\/ BEGIN generated content types\n[\s\S]*?\/\/ END generated content types/;
// The cache prefix is authored in brand.json, not in this worker.
const CACHE_PREFIX_PATTERN = /^const CACHE_PREFIX = '[a-z0-9-]+';$/m;

/** Files the service worker cannot work without; the generator always adds them. */
export const REQUIRED_FILES = Object.freeze(['index.html', 'src/main.js', 'assets/app.css', 'manifest.webmanifest']);

/**
 * The delivered app surface. One allowlist for the precache generator, the
 * Android bundler and the dev server: the page, its manifest, and everything
 * under assets/ and src/. The keystore, docs, tests, scripts and package.json
 * are repository files, never app files, so no reference to them may reach the
 * offline cache or the APK.
 */
export const SURFACE_FILES = Object.freeze(['index.html', 'manifest.webmanifest']);
export const SURFACE_ROOTS = Object.freeze(['assets', 'src']);

/**
 * Whether a path belongs to the app surface. The path is canonicalised through
 * resolve() first, so `assets/../android/keystore/…` is judged as
 * `android/keystore/…` and rejected — the raw string is never trusted.
 *
 * @param {string} relativePath repo-relative path (absolute paths are judged too)
 * @returns {boolean}
 */
export function isAllowed(relativePath, root = ROOT) {
  const absolute = resolve(root, String(relativePath ?? ''));
  const canonical = relative(root, absolute).split(sep).join('/');
  if (!canonical || canonical === '.' || canonical === '..' || canonical.startsWith('../')) return false;
  if (SURFACE_FILES.includes(canonical)) return true;
  return SURFACE_ROOTS.some((root) => canonical.startsWith(`${root}/`));
}

const GENERATED_HEADER = [
  '// Generated by scripts/precache.mjs — do not edit.',
  '// Source: index.html references, the src/main.js import graph, manifest icons,',
  '// and CSS url() assets; each file carries its own SHA-256 digest.',
  '// Regenerate with: npm run build',
  '',
].join('\n');

const EXTERNAL = /^(?:[a-z][a-z0-9+.-]*:|\/\/|#)/i;

/** Normalise a repo-relative path, then enforce the caller's surface allowlist. */
function normalise(relativePath, root = ROOT, allowed = isAllowed) {
  const cleaned = String(relativePath).replace(/\\/g, '/').replace(/^\.\//, '').replace(/^\/+/, '');
  if (!cleaned) throw new Error('empty file reference');
  const absolute = resolve(root, cleaned);
  if (absolute !== root && !absolute.startsWith(root + sep)) {
    throw new Error(`file reference escapes the repository: ${relativePath}`);
  }
  const canonical = relative(root, absolute).split(sep).join('/');
  if (!allowed(canonical, root)) {
    throw new Error(`file reference is outside the app surface (${[...SURFACE_FILES, ...SURFACE_ROOTS.map((entry) => `${entry}/**`)].join(', ')}): ${relativePath}`);
  }
  return canonical;
}

/**
 * Resolve one app-surface path to its real file.
 *
 * The allowlist is lexical, so a symlink inside assets/ or src/ that points at
 * the keystore passes it while every reader follows the link and ships the
 * bytes. This is the one owner of the real-path rule, shared by the manifest
 * generator, the Android bundler and the dev server: the lexical check runs
 * first, then the resolved path must still be inside the real repository.
 *
 * The surface belongs to the caller. The generator and the Android bundler keep
 * the precache allowlist; the dev server also serves `sw.js` and
 * `assets/precache.js`, which are deliberately outside that allowlist, so it
 * passes its own set instead of inheriting a predicate that would answer 403
 * for the worker.
 *
 * @param {string} relativePath repository-relative path
 * @param {{root?: string, allowed?: (canonical: string, root: string) => boolean}} [options]
 * @returns {Promise<{canonical: string, real: string}>}
 */
export async function resolveSurfacePath(relativePath, { root = ROOT, allowed = isAllowed } = {}) {
  const canonical = normalise(relativePath, root, allowed);
  const [real, realRoot] = await Promise.all([realpath(join(root, canonical)), realpath(root)]);
  if (real !== realRoot && !real.startsWith(realRoot + sep)) {
    throw new Error(`file reference resolves outside the repository (symlink): ${relativePath}`);
  }
  // Inside the repository is not enough: a link from assets/ to the keystore
  // stays under the root. The real target must be on the caller's surface too.
  const realCanonical = relative(realRoot, real).split(sep).join('/');
  if (!allowed(realCanonical, realRoot)) {
    throw new Error(`file reference resolves outside the app surface (symlink): ${relativePath}`);
  }
  return { canonical, real };
}

/** Local reference from an HTML attribute or a manifest icon. */
function localReference(reference) {
  if (!reference || EXTERNAL.test(reference)) return null;
  const withoutQuery = reference.split(/[?#]/)[0];
  return withoutQuery ? normalise(withoutQuery) : null;
}

async function assertFile(file) {
  let info;
  try {
    const { real } = await resolveSurfacePath(file);
    info = await stat(real);
  } catch (error) {
    if (error.code === 'ENOENT' || error.code === 'ENOTDIR') throw new Error(`precache entry does not exist: ${file}`);
    throw error;
  }
  if (!info.isFile()) throw new Error(`precache entry is not a file: ${file}`);
  return file;
}

/**
 * Remove comments while leaving string and template contents intact, so a
 * JSDoc `import('…')` example is not mistaken for a real dependency. This is a
 * view of the shared lexer — never a second scanner.
 */
export function stripComments(source) {
  return lexJavaScript(source).code;
}

/**
 * Static imports/re-exports and dynamic imports in one ES module. Both the
 * comment-stripped code and the string-literal mask come from the same lexer,
 * so a regex literal such as `/['"]/` cannot desynchronise them.
 */
export function moduleSpecifiers(source) {
  const specifiers = [];
  const { code, inside } = lexJavaScript(source);
  const patterns = [
    /(?:^|\n)\s*(?:import\s+(?:[^'"]*?\sfrom\s+)?|export\s+(?:[^'"]*?\sfrom\s+))["']([^"']+)["']/g,
    /\bimport\s*\(\s*["']([^"']+)["']\s*\)/g,
  ];
  for (const pattern of patterns) {
    for (const match of code.matchAll(pattern)) {
      if (inside[match.index]) continue;
      specifiers.push(match[1]);
    }
  }
  return specifiers;
}

/** Resolve an import specifier to an existing repo-relative module path. */
async function resolveModule(fromFile, specifier) {
  if (!specifier.startsWith('.')) return null;
  const base = resolve(ROOT, dirname(fromFile), specifier);
  const candidates = [base, `${base}.js`, join(base, 'index.js')];
  for (const candidate of candidates) {
    if (candidate !== ROOT && !candidate.startsWith(ROOT + sep)) {
      throw new Error(`${fromFile} imports a module outside the repository: ${specifier}`);
    }
    try {
      const info = await stat(candidate);
      if (info.isFile()) return candidate.slice(ROOT.length + 1).replace(/\\/g, '/');
    } catch {
      // Try the next candidate (extensionless import, directory index).
    }
  }
  throw new Error(`${fromFile} imports a module that does not exist: ${specifier}`);
}

/** Walk the module graph rooted at an entry module. */
export async function moduleGraph(entry = 'src/main.js') {
  const seen = new Set();
  const queue = [normalise(entry)];
  const modules = [];
  while (queue.length) {
    const file = queue.shift();
    if (seen.has(file)) continue;
    seen.add(file);
    await assertFile(file);
    modules.push(file);
    const source = await readFile(join(ROOT, file), 'utf8');
    for (const specifier of moduleSpecifiers(source)) {
      const candidate = await resolveModule(file, specifier);
      if (candidate && !seen.has(candidate)) queue.push(candidate);
    }
  }
  return modules.sort();
}

/** Local references declared by index.html. */
export function htmlReferences(html) {
  const references = [];
  for (const match of html.matchAll(/\b(?:src|href)\s*=\s*["']([^"']+)["']/gi)) {
    const reference = localReference(match[1]);
    if (reference) references.push(reference);
  }
  return references;
}

/** Icon sources declared by the web app manifest. */
export function manifestIcons(manifest) {
  const icons = Array.isArray(manifest?.icons) ? manifest.icons : [];
  return icons.map((icon) => localReference(icon?.src)).filter(Boolean);
}

const CSS_URL = /url\(\s*(?:"([^"]*)"|'([^']*)'|([^)'"\s]+))\s*\)/gi;

/**
 * Non-inline assets referenced by a stylesheet's url(). data:, http(s):,
 * protocol-relative and fragment-only references are not files this app can
 * cache; everything else resolves relative to the stylesheet and passes the
 * same app-surface allowlist as every other reference.
 *
 * @param {string} css stylesheet text
 * @param {string} fromFile repo-relative stylesheet path
 * @returns {string[]} repo-relative asset paths
 */
export function cssReferences(css, fromFile) {
  const withoutComments = String(css).replace(/\/\*[\s\S]*?\*\//g, ' ');
  const references = [];
  for (const match of withoutComments.matchAll(CSS_URL)) {
    const raw = (match[1] ?? match[2] ?? match[3] ?? '').trim();
    if (!raw || EXTERNAL.test(raw)) continue;
    const withoutQuery = raw.split(/[?#]/)[0].trim();
    if (!withoutQuery) continue;
    // A root-absolute URL is already relative to the served root; joining it to
    // the stylesheet directory produced assets/assets/x.
    references.push(withoutQuery.startsWith('/') ? normalise(withoutQuery) : normalise(join(dirname(fromFile), withoutQuery)));
  }
  return references;
}

/**
 * Collect the assets referenced by url() in a set of stylesheets, including
 * stylesheets referenced from another stylesheet.
 *
 * @param {Iterable<string>} files repo-relative paths already collected
 * @param {(file: string) => Promise<string>} readText injected for tests
 * @returns {Promise<string[]>} sorted repo-relative asset paths
 */
export async function collectStyleReferences(files, readText = (file) => readFile(join(ROOT, file), 'utf8')) {
  const found = new Set();
  const scanned = new Set();
  const queue = [...files].filter((file) => file.endsWith('.css'));
  while (queue.length) {
    const file = queue.shift();
    if (scanned.has(file)) continue;
    scanned.add(file);
    for (const reference of cssReferences(await readText(file), file)) {
      found.add(reference);
      if (reference.endsWith('.css') && !scanned.has(reference)) queue.push(reference);
    }
  }
  return [...found].sort();
}

/** Every file the service worker must cache for a cold offline start. */
export async function collectFiles() {
  const files = new Set();
  const add = async (file) => {
    if (!file) return;
    files.add(await assertFile(file));
  };

  const index = 'index.html';
  await add(index);
  const html = await readFile(join(ROOT, index), 'utf8');
  for (const reference of htmlReferences(html)) await add(reference);

  const manifest = JSON.parse(await readFile(join(ROOT, 'manifest.webmanifest'), 'utf8'));
  for (const icon of manifestIcons(manifest)) await add(icon);

  for (const module of await moduleGraph('src/main.js')) await add(module);
  for (const required of REQUIRED_FILES) await add(required);
  for (const style of await collectStyleReferences(files)) await add(style);

  return [...files].sort();
}

/**
 * Deterministic content hash over the sorted runtime files and their bytes,
 * plus a per-file SHA-256 the service worker re-checks on every staged body.
 */
export async function contentDigests(files) {
  const hash = createHash('sha256');
  const digests = {};
  for (const file of files) {
    const bytes = await readFile(join(ROOT, file));
    digests[file] = createHash('sha256').update(bytes).digest('hex');
    hash.update(`${file}\n${bytes.length}\n`);
    hash.update(bytes);
  }
  return { version: hash.digest('hex').slice(0, 16), digests };
}

/**
 * The exact text written to assets/precache.js.
 *
 * `navigationTimeoutMs` and the install retry budget are stamped from CONFIG so
 * the service worker — a classic script that cannot import src/core/config.js —
 * reads the one owner of the bounds instead of keeping a second literal.
 */
export function renderPrecache({
  version,
  files,
  required,
  digests,
  navigationTimeoutMs = CONFIG.offline.navigationTimeoutMs,
  installRetries = CONFIG.offline.installRetries,
  installRetryDelayMs = CONFIG.offline.installRetryDelayMs,
}) {
  const requiredEntries = required.map((file) => `    '${file}',`).join('\n');
  const entries = files.map((file) => `    '${file}',`).join('\n');
  const digestEntries = files.map((file) => `    '${file}': '${digests[file]}',`).join('\n');
  return `${GENERATED_HEADER}self.__PRECACHE = {\n  version: '${version}',\n  navigationTimeoutMs: ${navigationTimeoutMs},\n  installRetries: ${installRetries},\n  installRetryDelayMs: ${installRetryDelayMs},\n  required: [\n${requiredEntries}\n  ],\n  files: [\n${entries}\n  ],\n  digests: {\n${digestEntries}\n  },\n};\n`;
}

/** The exact text of the generated `<base>` helper block in sw.js. */
export function renderBaseHelper() {
  return [
    '// BEGIN generated base helper',
    '// Generated by scripts/precache.mjs from scripts/lib/base-href.mjs — do not edit.',
    injectBase.toString(),
    '// END generated base helper',
  ].join('\n');
}

/** The exact text of the generated content-type block in sw.js. */
export function renderContentTypes() {
  return [
    '// BEGIN generated content types',
    '// Generated by scripts/precache.mjs from scripts/lib/content-types.mjs — do not edit.',
    workerContentTypesSource(),
    '// END generated content types',
  ].join('\n');
}

/**
 * Replace the worker's build and cache-prefix stamps and its generated helper
 * block, requiring exactly one of each. The scalar patterns are anchored to
 * whole lines so a comment quoting an old value can never be rewritten while
 * the real constant stays stale. Every stamped fact is generated: the build
 * hash from the file graph, the prefix from brand.json, the helper from
 * scripts/lib/base-href.mjs, the content types from
 * scripts/lib/content-types.mjs.
 */
export function stampWorker(swSource, version, cachePrefix = BRAND.cachePrefix) {
  const source = String(swSource);
  const stamps = [
    [BUILD_PATTERN, 'build', `const BUILD = '${version}';`],
    [CACHE_PREFIX_PATTERN, 'cache prefix', `const CACHE_PREFIX = '${cachePrefix}';`],
    [BASE_HELPER_BLOCK, 'base helper', renderBaseHelper()],
    [CONTENT_TYPES_BLOCK, 'content types', renderContentTypes()],
  ];
  let stamped = source;
  for (const [pattern, label, replacement] of stamps) {
    const matches = [...source.matchAll(new RegExp(pattern.source, 'gm'))];
    if (matches.length !== 1) {
      throw new Error(`${SW_FILE} must contain exactly one ${label} stamp (${pattern}), found ${matches.length}`);
    }
    stamped = stamped.replace(pattern, replacement);
  }
  return stamped;
}

/** Build the manifest and the matching worker stamp in memory. */
export async function buildPrecache() {
  const files = await collectFiles();
  const { version, digests } = await contentDigests(files);
  const content = renderPrecache({
    version,
    files,
    required: REQUIRED_FILES,
    digests,
    navigationTimeoutMs: CONFIG.offline.navigationTimeoutMs,
    installRetries: CONFIG.offline.installRetries,
    installRetryDelayMs: CONFIG.offline.installRetryDelayMs,
  });
  const swSource = await readFile(join(ROOT, SW_FILE), 'utf8');
  const swContent = stampWorker(swSource, version, BRAND.cachePrefix);
  return { files, version, digests, content, swContent };
}

async function readExisting(file) {
  try {
    return await readFile(join(ROOT, file), 'utf8');
  } catch (error) {
    if (error.code === 'ENOENT') return null;
    throw error;
  }
}

/** Compare the manifest and worker stamp on disk with the graph. Never writes. */
export async function checkPrecache() {
  const built = await buildPrecache();
  const actual = await readExisting(OUTPUT);
  const swActual = await readExisting(SW_FILE);
  return {
    ...built,
    actual,
    swActual,
    ok: actual === built.content && swActual === built.swContent,
  };
}

async function writeAtomic(file, content) {
  const target = join(ROOT, file);
  const temporary = `${target}.${process.pid}.tmp`;
  try {
    await writeFile(temporary, content);
    await rename(temporary, target);
  } catch (error) {
    await rm(temporary, { force: true });
    throw error;
  }
}

/** Regenerate the manifest and stamp the worker atomically. */
export async function writePrecache() {
  const built = await buildPrecache();
  await writeAtomic(OUTPUT, built.content);
  await writeAtomic(SW_FILE, built.swContent);
  return built;
}

function describeDifference(label, expected, actual) {
  if (actual === null) return [`${label} does not exist`];
  const expectedLines = expected.split('\n');
  const actualLines = actual.split('\n');
  const changes = [];
  for (let index = 0; index < Math.max(expectedLines.length, actualLines.length) && changes.length < 6; index++) {
    if (expectedLines[index] === actualLines[index]) continue;
    changes.push(`line ${index + 1}: expected ${JSON.stringify(expectedLines[index] ?? '<eof>')}, found ${JSON.stringify(actualLines[index] ?? '<eof>')}`);
  }
  return changes;
}

async function main(argv) {
  const flags = argv.filter((argument) => argument.startsWith('--'));
  const unknown = flags.filter((flag) => flag !== '--write' && flag !== '--check');
  if (unknown.length) {
    console.error(`precache: unknown option ${unknown.join(', ')}`);
    console.error('usage: node scripts/precache.mjs [--write|--check]');
    return 2;
  }
  const write = flags.includes('--write');
  if (!write) {
    const result = await checkPrecache();
    if (result.ok) {
      console.log(`precache: up to date (${result.files.length} files, version ${result.version})`);
      return 0;
    }
    console.error(`precache: the generated files are stale — run: npm run build`);
    for (const line of describeDifference(OUTPUT, result.content, result.actual)) console.error(`  ${OUTPUT}: ${line}`);
    for (const line of describeDifference(SW_FILE, result.swContent, result.swActual)) console.error(`  ${SW_FILE}: ${line}`);
    return 1;
  }

  const result = await writePrecache();
  console.log(`precache: wrote ${OUTPUT} and ${SW_FILE} (${result.files.length} files, version ${result.version})`);
  return 0;
}

const invokedDirectly = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  main(process.argv.slice(2)).then(
    (code) => {
      process.exitCode = code;
    },
    (error) => {
      console.error(`precache: ${error.message}`);
      process.exitCode = 1;
    }
  );
}
