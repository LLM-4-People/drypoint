const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (path) => readFileSync(join(root, path), 'utf8');

function loadManifest() {
  const sandbox = { self: {} };
  vm.runInNewContext(read(OUTPUT), sandbox, { filename: OUTPUT });
  const manifest = sandbox.self.__PRECACHE;
  // Re-home the arrays/objects in this realm so deepEqual can compare them.
  return {
    version: manifest.version,
    files: Array.from(manifest.files),
    required: Array.from(manifest.required ?? []),
    digests: Object.fromEntries(Object.entries(manifest.digests ?? {})),
  };
}

const manifest = loadManifest();

function walk(directory) {
  const files = [];
  for (const entry of readdirSync(directory)) {
    const path = join(directory, entry);
    if (statSync(path).isDirectory()) files.push(...walk(path));
    else files.push(path);
  }
  return files;
}

test('every precache entry exists inside the repository', () => {
  assert.ok(Array.isArray(manifest.files) && manifest.files.length > 0, 'the manifest has files');
  assert.match(manifest.version, /^[0-9a-f]{16}$/, 'the version is a content hash');
  assert.match(read(OUTPUT), /^\/\/ Generated by scripts\/precache\.mjs/, 'generated-by header');

  for (const entry of manifest.files) {
    assert.ok(!isAbsolute(entry), `${entry} must be repo-relative`);
    assert.ok(!entry.split('/').includes('..'), `${entry} must not escape the repository`);
    const absolute = resolve(root, entry);
    assert.ok(absolute.startsWith(root + sep), `${entry} resolves inside the repository`);
    assert.ok(statSync(absolute).isFile(), `${entry} exists on disk`);
  }
});

test('the manifest is sorted, unique and covers every source module', () => {
  assert.deepEqual(manifest.files, [...new Set(manifest.files)].sort(), 'entries are sorted and unique');

  const modules = walk(join(root, 'src'))
    .filter((file) => file.endsWith('.js'))
    .map((file) => relative(root, file).replace(/\\/g, '/'));
  for (const module of modules) {
    assert.ok(manifest.files.includes(module), `precache includes ${module}`);
  }
  for (const required of ['index.html', 'assets/app.css', 'manifest.webmanifest', 'src/vendor/qrcode.js']) {
    assert.ok(manifest.files.includes(required), `precache includes ${required}`);
  }
});

