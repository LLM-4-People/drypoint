test('CSS url() assets are collected with the same allowlist', async () => {
  const css = [
    '.a { background: url("icon-192.png"); }',
    ".b { background: url('data:image/svg+xml,%3Csvg%3E'); }",
    '.c { background: url(https://cdn.test/x.png); }',
    '.d { background: url(#chevron); }',
    '.e { background: url(//cdn.test/y.png); }',
    '/* .f { background: url(gone.png); } */',
  ].join('\n');
  assert.deepEqual(cssReferences(css, 'assets/app.css'), ['assets/icon-192.png'], 'only a local, non-inline file survives');
  assert.deepEqual(
    await collectStyleReferences(['assets/app.css'], async () => css),
    ['assets/icon-192.png'],
    'the collector hands the asset to the precache pass'
  );
  assert.match(read('scripts/precache.mjs'), /collectStyleReferences\(files\)/, 'collectFiles consumes the stylesheet references');
  assert.throws(
    () => cssReferences('.x { background: url("../android/keystore/drypoint-release.jks"); }', 'assets/app.css'),
    /app surface/,
    'a stylesheet cannot reach the keystore either'
  );
});

test('the manifest never includes a repository-only file', () => {
  // The APK bundle (scripts/build-android.mjs) and the dev-server surface
  // (scripts/serve.mjs) are built from this generated list, so proving it here
  // proves all three surfaces.
  for (const entry of manifest.files) assert.ok(isAllowed(entry), `${entry} is inside the app surface`);
  for (const forbidden of ['docs/', 'android/keystore/', 'test/', 'scripts/']) {
    assert.deepEqual(manifest.files.filter((file) => file.startsWith(forbidden)), [], `no entry under ${forbidden}`);
  }
  assert.ok(!manifest.files.includes('package.json'), 'package.json is not served');
  assert.ok(!manifest.files.includes('sw.js'), 'the worker is served but never precached into itself');

  const build = read('scripts/build-android.mjs');
  assert.match(build, /isAllowed\(file\)/, 'syncAssets re-asserts the allowlist on the manifest entry');
  assert.match(build, /resolveSurfacePath\(file\)/, 'and resolves the real path through the shared owner');
  const serve = read('scripts/serve.mjs');
  assert.match(serve, /built\.files\.filter\(\(file\) => !isAllowed\(file\)\)/, 'the dev server derives its surface through the shared allowlist');
  assert.match(serve, /!allowed\.has\(key\)/, 'and serves nothing else');
});

test('the dev server decides from the allowlist before touching the filesystem', () => {
  const serve = read('scripts/serve.mjs');
  assert.match(serve, /import \{[^}]*isAllowed[^}]*\} from '\.\/precache\.mjs'/, 'the server imports the single owner');
  const guard = serve.indexOf('!allowed.has(key)');
  const open = serve.indexOf('resolveSurfacePath(key, {');
  assert.ok(guard >= 0, 'the allowlist guard is present');
  assert.ok(open > guard, 'the 404 guard runs before any path is resolved or read');
  assert.match(serve, /allowed: \(candidate\) => allowed\.has\(candidate\)/, 'the real-path check uses the server surface, not the precache allowlist');
  assert.doesNotMatch(serve, /const filePath = resolve\(join\(root, relative\)\)/, 'one resolver owns the real path');
});

/* ---------------- real paths and the worker stamp (R5-2/R5-3/R5-4) ---------------- */

test('a symlink to a repository-only file is rejected by the shared resolver', async () => {
  const dir = await mkdtemp(join(tmpdir(), 'drypoint-surface-'));
  await mkdir(join(dir, 'assets'), { recursive: true });
  await mkdir(join(dir, 'android', 'keystore'), { recursive: true });
  await writeFile(join(dir, 'assets', 'app.css'), 'body{}');
  await writeFile(join(dir, 'android', 'keystore', 'keystore.properties'), 'storePassword=secret');
  // The finding's case: lexically inside assets/, really the keystore.
  await symlink(join(dir, 'android', 'keystore', 'keystore.properties'), join(dir, 'assets', 'leak.css'));
  // A link that leaves the repository entirely.
  const outside = await mkdtemp(join(tmpdir(), 'drypoint-outside-'));
  await writeFile(join(outside, 'secret.txt'), 'secret');
  await symlink(join(outside, 'secret.txt'), join(dir, 'assets', 'escape.css'));

  const resolved = await resolveSurfacePath('assets/app.css', { root: dir });
  assert.equal(resolved.canonical, 'assets/app.css');
  assert.equal(resolved.real, join(dir, 'assets', 'app.css'), 'the real path is under the real root');

  // The default predicate is the precache surface: the collector (assertFile)
  // and the Android syncAssets both use this call shape.
  await assert.rejects(resolveSurfacePath('assets/leak.css', { root: dir }), /outside the app surface \(symlink\)/);
  await assert.rejects(resolveSurfacePath('assets/escape.css', { root: dir }), /symlink|outside the repository/);
  await assert.rejects(resolveSurfacePath('../keystore.properties', { root: dir }), /app surface|escapes/);

  // The dev server passes its own set, which also contains the worker and the
  // generated manifest. That set must accept them and still refuse a keystore
  // symlink whose key is allowed lexically: the exact call shape serve.mjs uses.
  await writeFile(join(dir, 'sw.js'), 'self.addEventListener("install", () => {});');
  await writeFile(join(dir, 'assets', 'precache.js'), 'self.__PRECACHE = {};');
  const serverAllowed = new Set(['sw.js', 'assets/precache.js', 'assets/app.css', 'assets/leak.css']);
  const serverSurface = (canonical) => serverAllowed.has(canonical);
  assert.equal((await resolveSurfacePath('sw.js', { root: dir, allowed: serverSurface })).real, join(dir, 'sw.js'));
  assert.equal((await resolveSurfacePath('assets/precache.js', { root: dir, allowed: serverSurface })).canonical, 'assets/precache.js');
  await assert.rejects(
    resolveSurfacePath('assets/leak.css', { root: dir, allowed: serverSurface }),
    /outside the app surface \(symlink\)/,
    'an allowed key whose real path is the keystore is still refused'
  );
});

