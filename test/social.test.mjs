/**
 * The generated social preview card and the metadata that points at it.
 *
 * The card is a generated asset with one owner, so these tests compare the SVG
 * with its renderer, read the PNG's pixels rather than its bytes, and prove the
 * deployment stages the file without adding it to the offline precache or the
 * Android bundle. The metadata tags are pinned to the brand owner and the card
 * descriptor, not to a second copy of the name or the description.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { mkdir, mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { NO_JEKYLL_FILE, SITE_DIR, SITE_ONLY_FILES, buildPages } from '../scripts/build-pages.mjs';
import { SOCIAL_CARD, checkSocial, renderSocialSvg } from '../scripts/build-social.mjs';
import { encodePng } from '../scripts/lib/png.mjs';
import { collectFiles, htmlReferences, readManifest } from '../scripts/precache.mjs';
import { PROBED_SITE_FILES, probeMethod, smokePaths } from '../scripts/smoke-pages.mjs';
import { projectRoot, readProjectFile as read } from './helpers/project-files.mjs';

const brand = JSON.parse(read('brand.json'));

async function walk(directory, prefix = '') {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) files.push(...(await walk(join(directory, entry.name), path)));
    else files.push(path);
  }
  return files.sort();
}

async function temporarySite(t) {
  const out = await mkdtemp(join(tmpdir(), 'drypoint-social-site-'));
  t.after(() => rm(out, { recursive: true, force: true }));
  return out;
}

test('the card SVG is the current renderer output with its generated-by header', () => {
  const svg = read(SOCIAL_CARD.svg);
  assert.equal(svg, renderSocialSvg(brand), 'run: npm run build:social -- --write');
  assert.match(svg, /^<!-- Generated by scripts\/build-social\.mjs; do not edit\. -->\n/);
  assert.match(svg, new RegExp(`width="${SOCIAL_CARD.width}" height="${SOCIAL_CARD.height}"`));
  assert.match(svg, /role="img"/, 'the artwork carries its accessible name');
});

test('the card PNG passes its one owner check', async () => {
  const result = await checkSocial();
  assert.deepEqual(result.findings, [], 'run: npm run build:social -- --write');
  assert.equal(result.checked, 1);
});

test('the card is staged beside the app and stays out of the offline surface', async (t) => {
  const runtime = await collectFiles();
  assert.equal(runtime.includes(SOCIAL_CARD.png), false, 'the card is not a precache file');
  assert.ok(SITE_ONLY_FILES.includes(SOCIAL_CARD.png), 'the deployment owner stages it');

  const manifest = await readManifest();
  assert.equal(manifest.files.includes(SOCIAL_CARD.png), false, 'the worker never caches the card');
  assert.equal(Object.hasOwn(manifest.digests, SOCIAL_CARD.png), false, 'the manifest has no card digest');
  assert.equal(
    htmlReferences(read('index.html')).includes(SOCIAL_CARD.png),
    false,
    'the absolute og:image is metadata, not a document reference'
  );

  const out = await temporarySite(t);
  await buildPages({ out });
  assert.deepEqual(await readFile(join(out, SOCIAL_CARD.png)), await readFile(join(projectRoot, SOCIAL_CARD.png)));
});

test('the staged site is 78 files and includes the card', async (t) => {
  const out = await temporarySite(t);
  await buildPages({ out });
  const staged = await walk(out);
  assert.equal(staged.length, 78, 'the deployment surface is pinned');
  assert.ok(staged.includes(SOCIAL_CARD.png), 'the card is one of the staged files');
});

test('the built _site tree, when present, is the same 78 files', async (t) => {
  const site = join(projectRoot, SITE_DIR);
  if (!existsSync(join(site, 'index.html'))) {
    t.skip(`run npm run pages:build to stage ${SITE_DIR}`);
    return;
  }
  const staged = await walk(site);
  assert.equal(staged.length, 78, `${SITE_DIR} is the deployment surface`);
  assert.ok(staged.includes(SOCIAL_CARD.png), `${SITE_DIR} publishes the card`);
  assert.deepEqual(await readFile(join(site, SOCIAL_CARD.png)), await readFile(join(projectRoot, SOCIAL_CARD.png)));
});

test('every Open Graph and Twitter tag is the brand and card value', () => {
  const html = read('index.html');
  const values = new Map();
  for (const [tag] of html.matchAll(/<meta\b[^>]*>/g)) {
    const key = tag.match(/\bproperty="([^"]+)"/)?.[1] ?? tag.match(/\bname="([^"]+)"/)?.[1];
    if (!key || !/^(?:og|twitter):/.test(key)) continue;
    assert.equal(values.has(key), false, `${key} is declared once`);
    values.set(key, tag.match(/\bcontent="([^"]*)"/)?.[1] ?? null);
  }

  const image = new URL(SOCIAL_CARD.png, brand.homepage).href;
  const expected = {
    'og:type': 'website',
    'og:site_name': brand.name,
    'og:title': brand.name,
    'og:description': brand.description,
    'og:url': brand.homepage,
    'og:image': image,
    'og:image:width': String(SOCIAL_CARD.width),
    'og:image:height': String(SOCIAL_CARD.height),
    'og:image:alt': SOCIAL_CARD.alt,
    'twitter:card': 'summary_large_image',
    'twitter:title': brand.name,
    'twitter:description': brand.description,
    'twitter:image': image,
    'twitter:image:alt': SOCIAL_CARD.alt,
  };
  assert.deepEqual([...values.keys()].sort(), Object.keys(expected).sort(), 'no missing or extra social tag');
  for (const [key, value] of Object.entries(expected)) assert.equal(values.get(key), value, key);

  const url = new URL(values.get('og:image'));
  assert.equal(url.protocol, 'https:');
  assert.equal(url.origin, new URL(brand.homepage).origin, 'the image shares the homepage origin');
  assert.equal(values.get('og:image:alt'), values.get('twitter:image:alt'), 'both cards share one alt');
  assert.ok(values.get('og:image:alt').trim().length > 0, 'the alt is not empty');
  assert.notEqual(values.get('og:image:alt'), values.get('og:title'), 'the alt describes the image, not the title');
  assert.equal(values.has('twitter:site'), false, 'no account is invented');
  for (const [key, value] of values) {
    assert.equal(String(value).includes(brand.repository), false, `${key} does not repeat the repository URL`);
  }
});

test('the deployment smoke probes the card and still skips the host marker', async () => {
  assert.ok(PROBED_SITE_FILES.includes(SOCIAL_CARD.png), 'the card is a probed deployment file');
  assert.equal(PROBED_SITE_FILES.includes(NO_JEKYLL_FILE), false, '.nojekyll is not app content');
  const paths = await smokePaths();
  assert.ok(paths.includes(`/${SOCIAL_CARD.png}`), 'the smoke requests the card');
  assert.equal(paths.includes(`/${NO_JEKYLL_FILE}`), false, 'the smoke never requests .nojekyll');
  assert.equal(probeMethod(`/${SOCIAL_CARD.png}`), 'HEAD', 'a binary deployment asset only has to answer');
});

test('the card check rejects a blank image at the right size', async (t) => {
  const root = await mkdtemp(join(tmpdir(), 'drypoint-social-check-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  await mkdir(join(root, 'assets'), { recursive: true });
  await writeFile(join(root, SOCIAL_CARD.svg), renderSocialSvg(brand));
  const data = Buffer.alloc(SOCIAL_CARD.width * SOCIAL_CARD.height * 4);
  for (let at = 0; at < data.length; at += 4) {
    data[at] = 8;
    data[at + 1] = 8;
    data[at + 2] = 10;
    data[at + 3] = 255;
  }
  await writeFile(join(root, SOCIAL_CARD.png), encodePng({ width: SOCIAL_CARD.width, height: SOCIAL_CARD.height, data }));

  const result = await checkSocial({ root, brand });
  assert.ok(result.findings.some((finding) => /near the accent/.test(finding)), 'the accent band is required');
  assert.ok(result.findings.some((finding) => /left half/.test(finding)), 'the wordmark is required');
  assert.ok(result.findings.some((finding) => /is blank/.test(finding)), 'a flat image is blank');
});
